/**
 * What a sound in `category` plays at, relative to the sound master — the
 * master button still scales everything on top of this. An unknown category
 * is 1.0, so a new sound is audible before anyone has decided where it sits.
 */
export function sfxGain(category) {
  const c = CONFIG.sfxMix[category];
  return CONFIG.sfxMaster * (c == null ? 1 : c);
}

/** The menu theme's share of the music bus, 0..1. Persisted. */

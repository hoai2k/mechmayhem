export const SPLIT_POST_MODES = ['auto', 'on', 'off'];

function readArenaDesign() {
  const p = params.get('design');
  if (ARENA_DESIGN_MODES.includes(p)) return p;
  if (params.get('procedural') === '1') return 'fallback';
  try {
    const v = localStorage.getItem('rw.arenaDesign');
    if (ARENA_DESIGN_MODES.includes(v)) return v;
    // migrate the retired on/off pref: ON meant "generate everything" (now
    // 'fallback'), OFF meant "play the hand-built levels" (now 'authored')
    const old = localStorage.getItem('rw.proceduralArenas');
    if (old === '1') return 'fallback';
    if (old === '0') return 'authored';
  } catch (e) { /* ok */ }
  return 'authored';
}

export function setArenaDesign(mode) {
  CONFIG.arenaDesign = ARENA_DESIGN_MODES.includes(mode) ? mode : 'authored';
  try { localStorage.setItem('rw.arenaDesign', CONFIG.arenaDesign); } catch (e) { /* ok */ }
  return CONFIG.arenaDesign;
}

function readSplitPost() {
  const p = params.get('postfx');
  if (p === 'single' || p === 'off') return 'off';
  if (p === 'on' || p === 'auto') return p;
  try {
    const v = localStorage.getItem('rw.splitPostFx');
    if (SPLIT_POST_MODES.includes(v)) return v;
  } catch (e) { /* ok */ }
  return 'auto';
}

export function setSplitPostFx(mode) {
  CONFIG.splitPostFx = SPLIT_POST_MODES.includes(mode) ? mode : 'auto';
  try { localStorage.setItem('rw.splitPostFx', CONFIG.splitPostFx); } catch (e) { /* ok */ }
  return CONFIG.splitPostFx;
}

function readPref(key, dflt = false) {
  try {
    const v = localStorage.getItem(key);
    return v === null ? dflt : v === '1';
  } catch (e) { return dflt; }
}

// A 0..1 knob whose default lives in this file and which a URL param can
// override for a quick try (?neonbuzz=0.25). Unlike readNum() there is no
// stored preference behind it — it is a value you EDIT here.
function readParam01(key, dflt) {
  const v = parseFloat(params.get(key));
  return Number.isFinite(v) ? Math.min(1, Math.max(0, v)) : dflt;
}

function readNum(key, dflt, lo = 0, hi = 1) {
  try {
    const v = parseFloat(localStorage.getItem(key));
    return Number.isFinite(v) ? Math.min(hi, Math.max(lo, v)) : dflt;
  } catch (e) { return dflt; }
}

